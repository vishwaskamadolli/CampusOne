import cookieParser from 'cookie-parser';
import cors from 'cors';
import express from 'express';
import rateLimit from 'express-rate-limit';
import helmet from 'helmet';
import swaggerUi from 'swagger-ui-express';
import { config } from './config.js';
import { openApiDocument } from './openapi.js';
import { authRouter } from './routes/auth.routes.js';
import { usersRouter } from './routes/users.routes.js';
import { academicsRouter } from './routes/academics.routes.js';
import { peopleRouter } from './routes/people.routes.js';
import { workflowsRouter } from './routes/workflows.routes.js';
import { timetablesRouter } from './routes/timetables.routes.js';
import { attendanceRouter } from './routes/attendance.routes.js';

export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: config.webUrl, credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use('/api/v1/auth/login', rateLimit({ windowMs: 15 * 60 * 1000, limit: 20, standardHeaders: true, legacyHeaders: false }));
app.use(['/api/v1/auth/forgot-password', '/api/v1/auth/reset-password'], rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: true, legacyHeaders: false }));
app.get('/api/v1/health', (_req, res) => res.json({ status: 'ok', service: 'campusone-api', timestamp: new Date().toISOString() }));
app.use('/api/v1/auth', authRouter);
app.use('/api/v1/users', usersRouter);
app.use('/api/v1/academics', academicsRouter);
app.use('/api/v1/people', peopleRouter);
app.use('/api/v1/timetables', timetablesRouter);
app.use('/api/v1/attendance', attendanceRouter);
app.use('/api/v1', workflowsRouter);
app.use('/docs', swaggerUi.serve, swaggerUi.setup(openApiDocument));
app.use((_req, res) => res.status(404).json({ message: 'Route not found' }));
app.use((error, _req, res, _next) => {
  console.error(error);
  if (error?.code === 11000) return res.status(409).json({ message: 'A record with these unique values already exists' });
  if (error?.name === 'ValidationError' || error?.name === 'CastError') return res.status(400).json({ message: error.message });
  res.status(500).json({ message: 'Internal server error' });
});
